// sw.js — щит раздела прошивальщика OBOD.
//
// Раньше корневой /sw.js принадлежал таймеру и получал запросы всего сайта: он гонял
// сеть наперегонки с таймаутом 800 мс и при задержке отдавал из кэша страницу
// таймера. Теперь работник таймера лежит в своей папке и чужие разделы не трогает;
// этот щит остаётся на случай, когда у посетителя ещё живёт старая регистрация
// с охватом всего сайта.
// Образ прошивки больше мегабайта, на медленном канале он не успевает за этот
// таймаут, и на его место вернулся бы HTML — установка сорвалась бы.
//
// Работник в этой папке регистрируется со своим охватом. Из двух подходящих
// регистраций страницу обслуживает та, у которой охват длиннее, поэтому страницы
// /obod/ обслуживает этот файл, а остальной сайт — корневой, как и раньше.
//
// Здесь только сеть: страница и образ и так берутся свежими, а кэш таймера сюда
// не вмешивается.
self.addEventListener('install', () => self.skipWaiting());

self.addEventListener('activate', (event) => event.waitUntil(self.clients.claim()));

self.addEventListener('fetch', (event) => {
    if (event.request.method !== 'GET') {
        return;
    }

    event.respondWith(fetch(event.request));
});